/** Field of a rune that carries the interpretation for a given topic. */
const TOPIC_FIELD: Record<TopicId, keyof Pick<Rune, "love" | "money" | "path" | "general">> = {
  love: "love",
  money: "money",
  path: "path",
  question: "general",
};

export function interpretationFor(rune: Rune, topic: TopicId): string {
  return rune[TOPIC_FIELD[topic]];
}

/** Sum of character codes of the trimmed, lowercased name. */
export function seedFromName(name: string): number {
  const normalized = name.trim().toLowerCase();
  let sum = 0;
  for (let i = 0; i < normalized.length; i += 1) {
    sum += normalized.charCodeAt(i);
  }
  return sum;
}

