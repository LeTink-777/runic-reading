function tone(runes: Rune[]): "strong" | "mixed" | "hard" {
  const positive = runes.filter((r) => r.energy === "positive").length;
  const challenging = runes.filter((r) => r.energy === "challenging").length;
  if (positive >= 2) return "strong";
  if (challenging >= 2) return "hard";
  return "mixed";
}

export interface Reading {
  rune1: Rune;
  rune2: Rune;
  rune3: Rune;
  overallMessage: string;
}

/**
 * Deterministic three-rune draw. The seed is the character-code sum of the name,
 * so the same name always receives the same spread.
 *
 * The three index formulas can never collide: the differences reduce to
 * 6s = 21, 12s = 13 and 6s = 16 (mod 24), none of which have solutions.
 */
export function drawRunes(name: string, topic: TopicId): Reading {
  const seed = seedFromName(name);
  const rune1 = RUNES[seed % 24];
  const rune2 = RUNES[(seed * 7 + 3) % 24];
  const rune3 = RUNES[(seed * 13 + 11) % 24];

  const overallMessage =
    `Твой расклад открывают ${rune1.name}, ${rune2.name} и ${rune3.name}: ` +
    `прошлое говорит о том, что ${rune1.keywords.split(",")[0]}, настоящее держится на том, что ${rune2.keywords.split(",")[0]}, ` +
    `а впереди тебя ждёт ${rune3.keywords.split(",")[0]}. ` +
    CLOSING[topic][tone([rune1, rune2, rune3])];

  return { rune1, rune2, rune3, overallMessage };
}
